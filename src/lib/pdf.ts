import jsPDF from 'jspdf';
import type { Note } from '../types';

export function exportNoteToPDF(note: Note): void {
  const doc = new jsPDF({ unit: 'pt', format: 'letter' });
  const margin = 60;
  const pageWidth = doc.internal.pageSize.getWidth();
  const maxWidth = pageWidth - margin * 2;
  let y = margin;

  doc.setFontSize(18);
  doc.setTextColor(14, 122, 95);
  doc.text('ClinNote — Clinical Progress Note', margin, y);
  y += 28;

  doc.setDrawColor(14, 122, 95);
  doc.setLineWidth(1);
  doc.line(margin, y, pageWidth - margin, y);
  y += 20;

  doc.setFontSize(10);
  doc.setTextColor(100, 100, 100);
  doc.text(`Client: ${note.client_name || 'N/A'}`, margin, y);
  doc.text(`Date: ${note.session_date}`, margin + 200, y);
  doc.text(`Format: ${note.note_format}`, margin + 360, y);
  y += 16;
  doc.text(`Session Type: ${note.session_type}`, margin, y);
  doc.text(`Generated: ${new Date(note.created_at).toLocaleDateString()}`, margin + 200, y);
  y += 24;

  doc.setDrawColor(220, 220, 220);
  doc.line(margin, y, pageWidth - margin, y);
  y += 20;

  doc.setFontSize(11);
  doc.setTextColor(26, 26, 46);

  const lines = note.content.split('\n');
  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed) {
      y += 8;
      continue;
    }

    const isBold = trimmed.startsWith('**') && trimmed.includes(':**');

    if (isBold) {
      const cleaned = trimmed.replace(/\*\*/g, '');
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(11);
      const split = doc.splitTextToSize(cleaned, maxWidth);
      for (const s of split) {
        if (y > doc.internal.pageSize.getHeight() - margin) {
          doc.addPage();
          y = margin;
        }
        doc.text(s, margin, y);
        y += 16;
      }
    } else {
      const cleaned = trimmed.replace(/\*\*/g, '');
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(10);
      const split = doc.splitTextToSize(cleaned, maxWidth);
      for (const s of split) {
        if (y > doc.internal.pageSize.getHeight() - margin) {
          doc.addPage();
          y = margin;
        }
        doc.text(s, margin, y);
        y += 14;
      }
    }
  }

  y += 40;
  doc.setDrawColor(220, 220, 220);
  doc.line(margin, y, margin + 200, y);
  y += 14;
  doc.setFontSize(9);
  doc.setTextColor(150);
  doc.text('Clinician Signature / Date', margin, y);

  y += 40;
  doc.setFontSize(8);
  doc.setTextColor(180);
  doc.text('Generated by ClinNote (clinnote.in) — HIPAA-compliant AI note generation', margin, y);
  doc.text('This note has been clinician-reviewed. Not a substitute for clinical judgment.', margin, y + 12);

  doc.save(`clinnote-${note.note_format}-${note.session_date}-${note.client_name || 'client'}.pdf`);
}
